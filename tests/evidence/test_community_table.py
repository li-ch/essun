"""The public community operating-point table: deterministic render,
gated by tests.

``tools/community_table.py`` rewrites the marked section of
``site/community.html`` from ``experiments/community/*.yaml``.  Two
properties are under test:

- determinism: the same record set renders byte-identically, ordered by
  (submitted, submission id), content escaped, no wall-clock;
- freshness: the committed page must match the committed records — the
  ``--check`` mode (and this test) fails otherwise, which is what makes
  the page display a new submission the moment its record lands:
  landing a record without re-rendering breaks the suite.

Also: the table refuses to render a review-less committed copy (pending
submissions live on the issue) and a ``published`` review whose
``verified_run_ids`` do not cover every cited run id — so a row cannot
reach the page by editing HTML or YAML alone.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import yaml

from essun.evidence.submissions import (
    SubmissionError,
    load_submission_file,
    render_table_rows,
)

REPO = Path(__file__).resolve().parents[2]
TABLE_TOOL = REPO / "tools" / "community_table.py"
PAGE = REPO / "site" / "community.html"
RECORDS_DIR = REPO / "experiments" / "community"
EXAMPLE = REPO / "examples" / "submission.example.yaml"


def submission_document() -> dict:
    return yaml.safe_load(EXAMPLE.read_text(encoding="utf-8"))


def review(verified: list[str], decision: str = "published") -> dict:
    return {
        "decision": decision,
        "reviewer": "@maintainer",
        "date": "2026-11-02",
        "basis": "re-ran the cited manifests; ids regenerated byte-for-byte",
        "verified_run_ids": verified,
    }


def write_record(tmp_path: Path, name: str, document: dict) -> Path:
    path = tmp_path / name
    path.write_text(yaml.safe_dump(document, sort_keys=True), encoding="utf-8")
    return path


def test_empty_table_renders_the_honest_empty_state():
    html = render_table_rows([])
    assert "No operating-point submissions recorded yet" in html
    assert "<table" not in html


def test_table_renders_a_reviewed_submission(tmp_path):
    document = submission_document()
    cited = [row["run_ids"][0] for row in document["results"]]
    document["review"] = review(cited)
    path = write_record(tmp_path, "sample.yaml", document)
    submission, rev = load_submission_file(path, at_door=False, repo_root=REPO)
    html = render_table_rows([(submission, rev)])
    assert "<table" in html
    assert "ring8-l64 vs ring8-l140" in html
    assert "differs on: topology" in html
    assert "1344" in html and "2408" in html
    assert "2ca54ead…" in html and "774cc400…" in html
    assert "published" in html


def test_table_renders_rejected_submissions_too(tmp_path):
    document = submission_document()
    document["review"] = review([], decision="rejected")
    path = write_record(tmp_path, "rejected.yaml", document)
    submission, rev = load_submission_file(path, at_door=False, repo_root=REPO)
    html = render_table_rows([(submission, rev)])
    assert "rejected" in html


def test_table_escapes_content(tmp_path):
    document = submission_document()
    document["submitter"] = "<script>alert('x')</script>"
    document["review"] = review([row["run_ids"][0] for row in document["results"]])
    path = write_record(tmp_path, "evil.yaml", document)
    submission, rev = load_submission_file(path, at_door=False, repo_root=REPO)
    html = render_table_rows([(submission, rev)])
    assert "<script>" not in html
    assert "&lt;script&gt;" in html


def test_table_ordering_is_deterministic(tmp_path):
    later = submission_document()
    later["submitted"] = "2026-11-05"
    later["review"] = review([row["run_ids"][0] for row in later["results"]])
    earlier = submission_document()
    earlier["submitted"] = "2026-11-01"
    earlier["review"] = review([row["run_ids"][0] for row in earlier["results"]])
    records = [
        load_submission_file(
            write_record(tmp_path, name, document), at_door=False, repo_root=REPO
        )
        for name, document in (("b_later.yaml", later), ("a_earlier.yaml", earlier))
    ]
    first = render_table_rows(records)
    second = render_table_rows(list(reversed(records)))
    assert first == second  # input order cannot change the render
    assert first.index("2026-11-01") < first.index("2026-11-05")


def test_table_refuses_a_reviewless_committed_copy(tmp_path):
    path = write_record(tmp_path, "pending.yaml", submission_document())
    try:
        load_submission_file(path, at_door=False, repo_root=REPO)
    except SubmissionError as error:
        assert "must carry a review block" in str(error)
    else:
        raise AssertionError("expected the gate to refuse a pending committed copy")


def test_table_refuses_an_uncovered_published_review(tmp_path):
    document = submission_document()
    document["review"] = review([document["results"][0]["run_ids"][0]])  # partial
    path = write_record(tmp_path, "partial.yaml", document)
    try:
        load_submission_file(path, at_door=False, repo_root=REPO)
    except SubmissionError as error:
        assert "requires every cited run id re-verified" in str(error)
    else:
        raise AssertionError("expected the gate to refuse an uncovered publish")


def test_committed_page_matches_committed_records():
    """The freshness gate: page and records must not drift apart."""
    proc = subprocess.run(
        [sys.executable, str(TABLE_TOOL), "--check"],
        capture_output=True,
        text=True,
    )
    assert proc.returncode == 0, (
        f"table is stale or invalid:\nstdout: {proc.stdout}\nstderr: {proc.stderr}"
    )
    assert "up to date" in proc.stdout


def test_committed_page_carries_the_markers():
    text = PAGE.read_text(encoding="utf-8")
    assert "TABLE:BEGIN" in text and "TABLE:END" in text


def test_committed_records_directory_exists_and_waits():
    assert RECORDS_DIR.is_dir()
    assert (RECORDS_DIR / "README.md").is_file()
    # zero records today: the honest starting state of the door
    assert list(RECORDS_DIR.glob("*.yaml")) == []
