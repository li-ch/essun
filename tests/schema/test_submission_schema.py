"""Schema contract for comparison submissions (v0).

``schemas/submission.schema.json`` is the shape of a submission document
(``examples/submission.example.yaml`` is the positive instance).  The
schema deliberately covers SHAPE only: the fairness gates (declared-axis
exactness, no shared-parameter shadowing, paired results, the delta-zero
control), the door's refusal of a self-written review, and the store
verification (submitted values must trace to the cited runs exactly)
live in ``essun.evidence.submissions``, where the whole submission is
available for cross-checking.  What the schema DOES freeze: run ids are
64-hex — a result without a run id is not even schema-valid — plus the
review decision vocabulary and ``format_version`` 0.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import jsonschema
import yaml

REPO = Path(__file__).resolve().parents[2]
SCHEMA = REPO / "schemas" / "submission.schema.json"
EXAMPLE = REPO / "examples" / "submission.example.yaml"


def load_schema() -> dict:
    return json.loads(SCHEMA.read_text(encoding="utf-8"))


def error_messages(instance: object) -> list[str]:
    messages: list[str] = []
    for error in jsonschema.Draft202012Validator(load_schema()).iter_errors(instance):
        messages.append(error.message)
        for context in error.context:
            messages.append(context.message)
    return messages


def _reject(instance: object, expected_substring: str) -> None:
    messages = error_messages(instance)
    assert messages, "expected validation to fail, but it passed"
    joined = "\n".join(messages)
    assert expected_substring in joined, (
        f"expected actionable message {expected_substring!r} not found in:\n{joined}"
    )


def valid_document() -> dict:
    return yaml.safe_load(EXAMPLE.read_text(encoding="utf-8"))


def test_schema_is_valid_draft202012():
    jsonschema.Draft202012Validator.check_schema(load_schema())


def test_example_validates():
    jsonschema.Draft202012Validator(load_schema()).validate(valid_document())


def test_example_with_well_formed_review_validates():
    document = valid_document()
    cited = [row["run_ids"][0] for row in document["results"]]
    document["review"] = {
        "decision": "published",
        "reviewer": "@maintainer",
        "date": "2026-11-02",
        "basis": "re-ran the cited manifests; both ids regenerated byte-for-byte",
        "verified_run_ids": cited,
    }
    jsonschema.Draft202012Validator(load_schema()).validate(document)


def test_missing_required_field_is_rejected():
    document = valid_document()
    del document["shared_parameters"]
    _reject(document, "'shared_parameters' is a required property")


def test_unknown_field_is_rejected():
    document = valid_document()
    document["confidence"] = "high"
    _reject(document, "Additional properties are not allowed")


def test_result_without_run_ids_is_not_schema_valid():
    document = valid_document()
    del document["results"][0]["run_ids"]
    _reject(document, "'run_ids' is a required property")


def test_run_id_of_wrong_shape_is_rejected():
    document = valid_document()
    document["results"][0]["run_ids"] = ["not-a-run-id"]
    _reject(document, "does not match")


def test_empty_run_ids_is_rejected():
    document = valid_document()
    document["results"][0]["run_ids"] = []
    _reject(document, "should be non-empty")


def test_non_exact_value_is_rejected():
    document = valid_document()
    document["results"][0]["value"] = "about 1344"
    _reject(document, "is not valid under any of the given schemas")


def test_wrong_format_version_is_rejected():
    document = valid_document()
    document["format_version"] = 1
    _reject(document, "0 was expected")


def test_three_arms_is_rejected():
    document = valid_document()
    document["arms"].append(copy.deepcopy(document["arms"][0]))
    _reject(document, "is too long")


def test_unknown_diff_axis_is_rejected():
    document = valid_document()
    document["comparison"]["differs_on"] = ["vibes"]
    _reject(document, "is not one of")


def test_review_with_unknown_decision_is_rejected():
    document = valid_document()
    document["review"] = {
        "decision": "celebrated",
        "reviewer": "@maintainer",
        "date": "2026-11-02",
        "basis": "looked fine",
        "verified_run_ids": [],
    }
    _reject(document, "is not one of ['published', 'rejected']")
