#!/usr/bin/env python3
"""community_table.py — render the public community operating-point table.

Reads every ``experiments/community/*.yaml`` (validated via
``essun.evidence.submissions`` — the maintainer path: a committed copy
must carry a review block, and a ``published`` review must list every
cited run id as re-verified), then rewrites the marked section of
``site/community.html`` between the TABLE markers with one row per
submission. Deterministic: rows sort by (submitted, submission_id), no
wall-clock, no host state — two renders of the same record set are
byte-identical, so the committed page can be gate-checked against the
committed records (tests/evidence/test_community_table.py), which is
what makes the page display a new submission the moment its record
lands: landing a record without re-rendering fails the suite.

Usage (repo root): python3 tools/community_table.py [--check]
  --check: exit 1 if the committed page is not up to date (CI mode).
Exit 0 on a clean render (or an up-to-date page with --check).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RECORDS_DIR = REPO / "experiments" / "community"
PAGE = REPO / "site" / "community.html"
BEGIN = "<!-- TABLE:BEGIN (generated by tools/community_table.py; edit outside the markers) -->"
END = "<!-- TABLE:END -->"


def load_records(records_dir: Path) -> list[tuple[dict, dict | None]]:
    """All valid submission/review pairs under ``records_dir``, sorted."""
    sys.path.insert(0, str(REPO / "src"))
    from essun.evidence.submissions import (  # noqa: E402 (path bootstrap first)
        SubmissionError,
        load_submission_file,
    )

    records: list[tuple[dict, dict | None]] = []
    failures: list[str] = []
    for path in sorted(records_dir.glob("*.yaml")) if records_dir.is_dir() else []:
        try:
            records.append(load_submission_file(path, at_door=False, repo_root=REPO))
        except SubmissionError as error:
            failures.append(str(error))
    if failures:
        for failure in failures:
            print(f"community-table: INVALID RECORD: {failure}", file=sys.stderr)
        raise SystemExit(1)
    return records


def render_page(page_text: str, table_html: str) -> str:
    if BEGIN not in page_text or END not in page_text:
        raise SystemExit(
            "community-table: page markers missing from site/community.html"
        )
    before, rest = page_text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return f"{before}{BEGIN}\n{table_html}      {END}{after}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed page matches the records; exit 1 if not",
    )
    args = parser.parse_args(argv)

    records = load_records(RECORDS_DIR)
    sys.path.insert(0, str(REPO / "src"))
    from essun.evidence.submissions import render_table_rows  # noqa: E402

    table_html = render_table_rows(records)
    current = PAGE.read_text(encoding="utf-8")
    rendered = render_page(current, table_html)

    if args.check:
        if rendered != current:
            print(
                "community-table: STALE — site/community.html does not match "
                "experiments/community/ (run: python3 tools/community_table.py)",
                file=sys.stderr,
            )
            return 1
        print(
            f"community-table: PASS — page up to date with {len(records)} record(s)"
        )
        return 0

    PAGE.write_text(rendered, encoding="utf-8")
    print(f"community-table: rendered {len(records)} record(s) into {PAGE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
