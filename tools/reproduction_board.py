#!/usr/bin/env python3
"""reproduction_board.py — render the public reproduction board.

Reads every ``experiments/reproductions/*.yaml`` (validated via
``essun.evidence.reproductions`` — an invalid record fails the render,
and a record may not assert the label without the adjudication gate's
support), then rewrites the marked section of
``site/reproductions.html`` between the BOARD markers with one row per
attempt. Deterministic: rows sort by (reported, reproduction_id), no
wall-clock, no host state — two renders of the same record set are
byte-identical, so the committed page can be gate-checked against the
committed records (tests/evidence/test_reproduction_board.py), which is
what makes the page display a new attempt the moment its record lands:
landing a record without re-rendering fails the suite.

Usage (repo root): python3 tools/reproduction_board.py [--check]
  --check: exit 1 if the committed page is not up to date (CI mode).
Exit 0 on a clean render (or an up-to-date page with --check).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RECORDS_DIR = REPO / "experiments" / "reproductions"
PAGE = REPO / "site" / "reproductions.html"
BEGIN = "<!-- BOARD:BEGIN (generated by tools/reproduction_board.py; edit outside the markers) -->"
END = "<!-- BOARD:END -->"


def load_records(records_dir: Path) -> list[tuple[dict, dict | None]]:
    """All valid attempt/adjudication pairs under ``records_dir``, sorted."""
    sys.path.insert(0, str(REPO / "src"))
    from essun.evidence.reproductions import (  # noqa: E402 (path bootstrap first)
        ReproductionError,
        load_reproduction_file,
    )

    records: list[tuple[dict, dict | None]] = []
    failures: list[str] = []
    for path in sorted(records_dir.glob("*.yaml")) if records_dir.is_dir() else []:
        try:
            records.append(load_reproduction_file(path))
        except ReproductionError as error:
            failures.append(str(error))
    if failures:
        for failure in failures:
            print(f"reproduction-board: INVALID RECORD: {failure}", file=sys.stderr)
        raise SystemExit(1)
    return records


def render_page(page_text: str, board_html: str) -> str:
    if BEGIN not in page_text or END not in page_text:
        raise SystemExit(
            "reproduction-board: page markers missing from site/reproductions.html"
        )
    before, rest = page_text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return f"{before}{BEGIN}\n{board_html}      {END}{after}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed page matches the records; exit 1 if not",
    )
    args = parser.parse_args(argv)

    records = load_records(RECORDS_DIR)
    sys.path.insert(0, str(REPO / "src"))
    from essun.evidence.reproductions import render_board_rows  # noqa: E402

    board_html = render_board_rows(records)
    current = PAGE.read_text(encoding="utf-8")
    rendered = render_page(current, board_html)

    if args.check:
        if rendered != current:
            print(
                "reproduction-board: STALE — site/reproductions.html does not "
                "match experiments/reproductions/ (run: python3 tools/reproduction_board.py)",
                file=sys.stderr,
            )
            return 1
        print(
            f"reproduction-board: PASS — page up to date with {len(records)} record(s)"
        )
        return 0

    PAGE.write_text(rendered, encoding="utf-8")
    print(f"reproduction-board: rendered {len(records)} record(s) into {PAGE.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
