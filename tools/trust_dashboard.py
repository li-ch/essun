#!/usr/bin/env python3
"""trust_dashboard.py — render the public trust dashboard.

Three modes, one state: the committed snapshot
``experiments/trust/indicators.yaml`` is the only source of page bytes.

- default: re-derive the tree-derived counts (reproduction attempts,
  adjudicated external reproductions, community submissions) at HEAD,
  merge them into the snapshot, write it, and rewrite the marked
  section of ``site/trust.html`` between the DASHBOARD markers.
- ``--check``: no writes; fail if the committed page is not the render
  of the committed snapshot, or if the snapshot's tree-derived counts
  have drifted from the tree (CI mode — landing a record without
  re-rendering fails the suite, exactly like the reproduction board and
  the community table).
- ``--fetch``: additionally read the fetched sections from their public
  sources (GitHub REST API for issues and pull requests of the
  configured repository; Semantic Scholar for citations, only when an
  arXiv id is configured in ``experiments/trust/sources.yaml``), then
  render.  A failed fetch exits non-zero BEFORE anything is written:
  the page keeps its last committed values and the failure is visible,
  never silently absorbed into a zero.

No number passes through a human hand.  Usage (repo root):
python3 tools/trust_dashboard.py [--check|--fetch]
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SNAPSHOT = REPO / "experiments" / "trust" / "indicators.yaml"
SOURCES = REPO / "experiments" / "trust" / "sources.yaml"
PAGE = REPO / "site" / "trust.html"
BEGIN = "<!-- DASHBOARD:BEGIN (generated by tools/trust_dashboard.py; edit outside the markers) -->"
END = "<!-- DASHBOARD:END -->"

S2_PAPER_URL = "https://api.semanticscholar.org/graph/v1/paper/arXiv:{arxiv_id}?fields=citationCount"
RETRIES = 3
RETRY_SLEEP_S = 5.0


def _head_commit(repo: Path) -> str:
    proc = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise SystemExit(f"trust-dashboard: cannot resolve HEAD commit ({proc.stderr.strip()})")
    return proc.stdout.strip()


def _utc_today() -> str:
    return datetime.datetime.now(datetime.timezone.utc).date().isoformat()


def _http_json(url: str, token: str | None) -> dict:
    """One GET returning parsed JSON; raises on HTTP/network error."""
    request = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json"})
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    # GitHub requires a User-Agent; Semantic Scholar tolerates one.
    request.add_header("User-Agent", "essun-trust-dashboard")
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read().decode("utf-8"))


def _http_json_retry(url: str, token: str | None, what: str) -> dict:
    last: Exception | None = None
    for attempt in range(RETRIES):
        try:
            return _http_json(url, token)
        except urllib.error.HTTPError as error:
            if 400 <= error.code < 500 and error.code != 403:  # 403 can be rate limiting
                raise SystemExit(
                    f"trust-dashboard: FETCH FAILED — {what}: HTTP {error.code} "
                    f"({url}); nothing was written"
                )
            last = error
        except (urllib.error.URLError, TimeoutError, OSError, json.JSONDecodeError) as error:
            last = error
        if attempt < RETRIES - 1:
            time.sleep(RETRY_SLEEP_S)
    raise SystemExit(
        f"trust-dashboard: FETCH FAILED — {what}: {last} ({url}); nothing was written"
    )


def fetch_github(repository: str) -> dict:
    """Issues and pull requests, total and from strangers, all states.

    Paginates ``/issues?state=all`` (interleaved pull requests are
    excluded inside :func:`aggregate_github`) and ``/pulls?state=all``;
    refuses to count past MAX_PAGES pages — a truncated count is a wrong
    count, so the fetch fails instead.
    """
    sys.path.insert(0, str(REPO / "src"))
    from essun.evidence.trust import MAX_PAGES, aggregate_github  # noqa: E402

    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")

    def paged(endpoint: str, what: str) -> list:
        entries: list = []
        for page in range(1, MAX_PAGES + 1):
            url = f"https://api.github.com/repos/{repository}/{endpoint}?state=all&per_page=100&page={page}"
            batch = _http_json_retry(url, token, what)
            if not isinstance(batch, list):
                raise SystemExit(f"trust-dashboard: FETCH FAILED — {what} returned a non-list")
            entries.extend(batch)
            if len(batch) < 100:
                return entries
        raise SystemExit(
            f"trust-dashboard: FETCH FAILED — {what} exceeds {MAX_PAGES * 100} records; "
            "the pagination cap refuses to report a partial count"
        )

    issues = paged("issues", "issues listing")
    pulls = paged("pulls", "pull requests listing")
    counts = aggregate_github(issues, pulls)
    print(
        f"trust-dashboard: fetched {counts['issues_total']} issue(s) "
        f"({counts['issues_from_strangers']} from strangers), "
        f"{counts['pulls_total']} pull request(s) "
        f"({counts['pulls_from_strangers']} from strangers) from {repository}"
    )
    return counts


def fetch_citations(sources: dict) -> tuple[int | None, str]:
    """The citation count, or None with the honest reason.

    No arXiv id configured -> not measurable (the paper is not public;
    unknown is not zero).  Configured but not indexed yet -> not
    measurable.  Indexed -> the count Semantic Scholar reports, zero or
    not.
    """
    arxiv_id = sources.get("arxiv_id")
    if arxiv_id is None:
        return (
            None,
            "no public paper to count citations of yet — the arXiv id is recorded in "
            "experiments/trust/sources.yaml when the paper exists",
        )
    url = S2_PAPER_URL.format(arxiv_id=arxiv_id)
    token = os.environ.get("S2_API_KEY")  # optional; the unauthenticated pool suffices weekly
    try:
        document = _http_json_retry(url, token, "citations lookup")
    except SystemExit:
        raise
    count = document.get("citationCount")
    if isinstance(count, bool) or not isinstance(count, int) or count < 0:
        raise SystemExit(
            f"trust-dashboard: FETCH FAILED — citations lookup returned an unusable "
            f"count {count!r}; nothing was written"
        )
    note = f"Semantic Scholar citation count for arXiv:{arxiv_id}"
    print(f"trust-dashboard: fetched citation count {count} for arXiv:{arxiv_id}")
    return count, note


def render_page(page_text: str, dashboard_html: str) -> str:
    if BEGIN not in page_text or END not in page_text:
        raise SystemExit("trust-dashboard: page markers missing from site/trust.html")
    before, rest = page_text.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    return f"{before}{BEGIN}\n{dashboard_html}      {END}{after}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="verify page and snapshot; exit 1 on drift")
    modes.add_argument("--fetch", action="store_true", help="refresh fetched sections from public APIs, then render")
    args = parser.parse_args(argv)

    sys.path.insert(0, str(REPO / "src"))
    from essun.evidence.trust import (  # noqa: E402
        TrustError,
        derive_repo,
        dump_snapshot,
        load_snapshot,
        load_sources,
        repo_drift,
        render_dashboard_rows,
        validate_snapshot,
    )

    current = load_snapshot(SNAPSHOT)
    today = _utc_today()

    if args.fetch:
        sources = load_sources(SOURCES)
        github_counts = fetch_github(sources["github_repository"])
        citation_count, citation_note = fetch_citations(sources)
        current["github"] = {
            "repository": sources["github_repository"],
            "as_of": today,
            **github_counts,
        }
        current["citations"] = {
            "source": "semanticscholar",
            "arxiv_id": sources["arxiv_id"],
            "as_of": today,
            "count": citation_count,
            "note": citation_note,
        }

    derived = derive_repo(REPO, _head_commit(REPO))
    if args.check:
        problems: list[str] = []
        repo_drift(problems, derived, current)
        rendered = render_page(PAGE.read_text(encoding="utf-8"), render_dashboard_rows(current))
        if rendered != PAGE.read_text(encoding="utf-8"):
            problems.append(
                "site/trust.html is not the render of experiments/trust/indicators.yaml "
                "(run: python3 tools/trust_dashboard.py)"
            )
        if problems:
            for problem in problems:
                print(f"trust-dashboard: {problem}", file=sys.stderr)
            return 1
        print("trust-dashboard: PASS — page and snapshot match the tree")
        return 0

    current["repo"] = derived
    try:
        validate_snapshot(current)
    except TrustError as error:
        raise SystemExit(f"trust-dashboard: refusing to write an invalid snapshot: {error}")
    SNAPSHOT.write_text(dump_snapshot(current), encoding="utf-8")
    rendered = render_page(PAGE.read_text(encoding="utf-8"), render_dashboard_rows(current))
    PAGE.write_text(rendered, encoding="utf-8")
    print(
        f"trust-dashboard: rendered {PAGE.relative_to(REPO)} from {SNAPSHOT.relative_to(REPO)} "
        f"(repo counts at commit {derived['as_of_commit'][:12]})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
