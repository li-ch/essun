#!/usr/bin/env python
"""profile_matrix.py — profile-surface matrix across fabric semantic profiles.

Renders a summary table of one or more essun-profile v0.1 artifacts: per
fabric, its source access class, requirement counts by disposition, free
parameters, backend bindings, supported surface, calibration status, and
known omissions. This is the PROFILE-level view (what each fabric's spec
surface says); the run-level cross-fabric matrix
(tools/cross_fabric_matrix.py) stays artifact-based and unchanged.

Usage:
    .venv/bin/python tools/profile_matrix.py [paths... | --profile-dir DIR]
        # prints markdown; every profile must pass the format loader
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from essun.specir.profile_format import load_profile

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))


def build_rows(profile_paths) -> list[dict]:
    rows = []
    for path in profile_paths:
        loaded = load_profile(path)  # loud failure on any invalid profile
        dispositions = loaded.disposition_counts()  # all six keys, zeros kept
        rows.append(
            {
                "profile_path": str(path),
                "profile_id": loaded.profile_id,
                "profile_version": loaded.profile_version,
                "access": loaded.provenance.access,
                "requirements": len(loaded.requirements),
                "dispositions": dispositions,
                "free_parameters": len(loaded.freedom),
                "bindings": len(loaded.bindings),
                "checks": len(loaded.checks),
                "workloads": list(loaded.supported.workloads),
                "observables": list(loaded.supported.observables),
                "calibration": loaded.calibration.status,
                "omissions": len(loaded.omissions),
            }
        )
    return rows


def render_markdown(rows: list[dict]) -> str:
    lines = [
        "# Fabric profile-surface matrix",
        "",
        "Profile-level view (spec surface per fabric); generated by "
        "`tools/profile_matrix.py`; every row passed the essun-profile "
        "format loader.",
        "",
        "| profile | version | access | reqs (by disposition) | free params | bindings | checks | workloads | observables | calibration | omissions |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        disp = ", ".join(
            f"{count} {name}"
            for name, count in sorted(row["dispositions"].items())
        ) or "0"
        lines.append(
            f"| `{row['profile_id']}` | {row['profile_version']} | {row['access']} "
            f"| {row['requirements']} ({disp}) | {row['free_parameters']} "
            f"| {row['bindings']} | {row['checks']} "
            f"| {', '.join(row['workloads'])} | {', '.join(row['observables'])} "
            f"| {row['calibration']} | {row['omissions']} |"
        )
    lines.append("")
    lines.append(
        "NOT SAMPLED: a profile row describes the spec surface only — it "
        "asserts nothing about measured performance; run-level comparison "
        "lives in the cross-fabric matrix."
    )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("paths", nargs="*", help="semantic_profile.yaml paths")
    parser.add_argument(
        "--profile-dir", type=Path, default=None,
        help="load every semantic_profile.yaml under this directory (recursive)",
    )
    args = parser.parse_args(argv)

    paths = [Path(p) for p in args.paths]
    if args.profile_dir is not None:
        paths.extend(sorted(args.profile_dir.rglob("semantic_profile.yaml")))
    if not paths:
        repo_profiles = sorted((REPO / "experiments").glob("*/semantic_profile.yaml"))
        paths = repo_profiles
    if not paths:
        print("no profiles found", file=sys.stderr)
        return 1

    sys.stdout.write(render_markdown(build_rows(paths)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
