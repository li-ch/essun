def reproduction_id(attempt: Mapping) -> str:
    """Content address of an attempt: SHA-256 over its canonical JSON.

    The adjudication is deliberately outside the address: judging an
    attempt must not rewrite its identity.  Callers validate first (an
    invalid attempt has an address that will never be stored).
    """
    from .store import canonical_json  # deferred: store imports this module

    return hashlib.sha256(canonical_json(attempt).encode("utf-8")).hexdigest()


def effective_label(attempt: Mapping, adjudication: Mapping | None) -> str:
    """The effective label of an attempt, from its adjudication alone.

    UNKNOWN when there is no adjudication — the state every attempt in
    this repository is recorded in until the verification procedure runs.
    The EXTERNALLY_REPRODUCED reading is only reachable through an
    adjudication that passed the cross-field gate (which
    :func:`validate_adjudication` enforces wherever records enter).
    """
    if not adjudication:
        return UNKNOWN
    verdict = adjudication.get("verdict")
    return {
        "externally_reproduced": "EXTERNALLY_REPRODUCED",
        "not_independent": "NOT_INDEPENDENT",
        "not_counted": "NOT_COUNTED",
    }.get(verdict, UNKNOWN)


def load_reproduction_file(path: Path | str) -> tuple[dict, dict | None]:
    """Parse and validate one committed reproduction YAML file.

    The file holds the attempt fields at top level plus an optional
    ``adjudication`` block; the returned pair is ``(attempt,
    adjudication or None)`` with the adjudication cross-checked against
    the attempt (the gate runs — a committed file may not assert the
    label without the support the gate demands).  Raises
    :class:`ReproductionError` on any problem, naming the file.
    """
    path = Path(path)
    import yaml  # local import: stdlib-free module otherwise, like the store

    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise ReproductionError(f"{path.name}: unreadable ({error})") from error
    except yaml.YAMLError as error:
        raise ReproductionError(f"{path.name}: invalid YAML ({error})") from error
    if not isinstance(document, dict):
        raise ReproductionError(f"{path.name}: must be a mapping of record fields")

    adjudication = document.pop("adjudication", None)
    attempt = document
    problems = reproduction_problems(attempt)
    if problems:
        raise ReproductionError(f"{path.name}: " + "; ".join(problems))
    if adjudication is not None:
        problems = adjudication_problems(adjudication, attempt)
        if problems:
            raise ReproductionError(f"{path.name}: " + "; ".join(problems))
    return dict(attempt), dict(adjudication) if adjudication is not None else None


def render_board_rows(records: list[tuple[dict, dict | None]]) -> str:
    """Deterministic HTML for the public board, one ``<tr>`` per attempt.

    Input order is ignored: rows sort by (reported date, reproduction
    id), so two renders of the same record set are byte-identical.  The
    label column shows :func:`effective_label` — UNKNOWN until an
    adjudication lands, which is the point of the page.  Content is
    escaped; no wall-clock, no host state.
    """
    import html

    def escape(value: Any) -> str:
        return html.escape(str(value), quote=True)

    def short(run_id: str) -> str:
        return f"{run_id[:8]}…" if len(run_id) > 8 else run_id

    ordered = sorted(
        records,
        key=lambda pair: (pair[0].get("reported", ""), reproduction_id(pair[0])),
    )
    if not ordered:
        return (
            '      <p class="note">No reproduction attempts recorded yet. '
            "When one is reported on the funnel issue, it is transcribed into "
            "<code>experiments/reproductions/</code> and appears here on the "
            "next board render — attempts are listed whether they succeed, "
            "diverge, or stop early, and nothing is filtered.</p>\n"
        )
    lines = [
        '      <table class="board">',
        "        <thead>",
        "          <tr><th>Reported</th><th>Reproducer</th><th>Commit</th>"
        "<th>Outcome</th><th>Runs</th><th>Label</th></tr>",
        "        </thead>",
        "        <tbody>",
    ]
    for attempt, adjudication in ordered:
        label = effective_label(attempt, adjudication)
        label_class = {
            "EXTERNALLY_REPRODUCED": "label label-external",
            "NOT_INDEPENDENT": "label label-proposed",
            "NOT_COUNTED": "label label-proposed",
        }.get(label, "label label-unverified")
        lines.append(
            "          <tr>"
            f"<td>{escape(attempt['reported'])}</td>"
            f"<td>{escape(attempt['reproducer'])}</td>"
            f"<td><code>{escape(attempt['reproduced_at_commit'][:12])}</code></td>"
            f"<td>{escape(attempt['outcome'])}</td>"
            f"<td><code>{escape(' '.join(short(r) for r in attempt['reproduced_run_ids']))}</code></td>"
            f'<td><span class="{label_class}">{escape(label)}</span></td>'
            "</tr>"
        )
    lines.append("        </tbody>")
    lines.append("      </table>")
    return "\n".join(lines) + "\n"


def _store_main(argv: list[str] | None = None) -> int:
    """CLI: validate committed record files against a local store.

    Usage: ``python -m essun.evidence.reproductions <repo-root>`` —
    validates every ``experiments/reproductions/*.yaml`` (structure,
    cross-field gates) and, for each attempt whose run ids are all
    present in the local store under ``results/``, appends the attempt
    (and its adjudication) to the append-only index.  Attempts whose run
    ids are not yet rebuilt locally are reported and skipped — the store
    only ever records what it can verify.  Exit non-zero on any invalid
    record; otherwise prints what was appended.
    """
    import sys

    from .store import EvidenceStore

    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 1:
        print("usage: python -m essun.evidence.reproductions <repo-root>", file=sys.stderr)
        return 2
    root = Path(argv[0])
    records_dir = root / "experiments" / "reproductions"
    store = EvidenceStore(root / "results")
    known_runs = set(store.list_runs())
    failures = 0
    appended = 0
    for path in sorted(records_dir.glob("*.yaml")) if records_dir.is_dir() else []:
        try:
            attempt, adjudication = load_reproduction_file(path)
        except ReproductionError as error:
            print(f"INVALID {path.name}: {error}", file=sys.stderr)
            failures += 1
            continue
        missing = [r for r in attempt["reproduced_run_ids"] if r not in known_runs]
        if missing:
            print(
                f"SKIP {path.name}: {len(missing)} run id(s) not in local store "
                "(rebuild the cited runs first)"
            )
            continue
        rid = store.put_reproduction(attempt)
        appended += 1
        if adjudication is not None:
            store.put_adjudication(adjudication, rid)
    print(f"reproductions: {appended} appended, {failures} invalid")
    return 1 if failures else 0


if __name__ == "__main__":  # pragma: no cover - thin CLI shell
    raise SystemExit(_store_main())
