"""External-reproduction records: the top rung's machinery, unloaded.

The public label ladder's top rung — ``EXTERNALLY_REPRODUCED`` — has never
been exercised: no one outside this repository's authors has executed a
released run and reported it.  This module builds the record type that a
future report is transcribed into, with one design rule that overrides
every other: **the record defaults to unknown and can never assert the
label by itself.**

Two phases, two record kinds (both append-only once in the store):

1. an ATTEMPT — what a public report establishes on its face: who ran it,
   from which commit, in which environment, which stored run ids, and
   with what outcome (``byte_identical`` / ``diverged`` / ``incomplete``).
   An attempt carries an ``independence`` block in which every criterion
   is ``null`` — UNKNOWN, per :mod:`essun.evidence.dimensions`' absence
   semantics — because a report about oneself is not a judgment about
   oneself.  A record that arrives with a self-judged criterion (any
   non-null value) is INVALID at the door: judgments belong to the
   adjudication, and the transcription may not make them.

2. an ADJUDICATION — the maintainer action that applies the verification
   procedure (``docs/reproduction-policy.md``) and records its verdict.
   This is the ONLY path by which the effective label of a reproduction
   stops being UNKNOWN, and the store-side validation mechanically
   refuses a verdict of ``externally_reproduced`` unless

   - the attempt's outcome is ``byte_identical``,
   - ALL FOUR independence criteria are judged ``met: true`` with a
     non-empty note each, and
   - the reproducer is not one of the repository's author identities
     (:data:`AUTHOR_IDENTITIES`, the mechanical floor of "different
     hands"; the human judgment and its limits are recorded in the
     adjudication's ``basis``).

   A divergence is never an ``externally_reproduced`` data point — it
   enters the counterexample path (minimize, then classify; never tune),
   and the attempt's ``divergence_notes`` carry the pointer.

Identity: ``reproduction_id`` is the SHA-256 of the canonical-JSON
ATTEMPT fields (adjudication excluded), so recording the identical
attempt is idempotent while an adjudication, a correction, or a new
judgment appends new content and never rewrites the attempt.  The
effective label (:func:`effective_label`) is a pure function of the
attempt plus its adjudication: absent adjudication, or one that does not
satisfy the gate above, reads as UNKNOWN — "not yet established" — which
is the honest reading of every reproduction in this repository today.

Committed surface: attempts wait as YAML files under
``experiments/reproductions/`` (``results/`` is git-ignored and rebuilt;
the durable citation is the committed transcription plus the public
report it points at).  :func:`load_reproduction_file` parses and
validates one file; ``tools/reproduction_board.py`` renders the public
board from that directory; ``EvidenceStore.put_reproduction`` /
``put_adjudication`` carry both kinds into the append-only store index
``results/reproductions.jsonl`` once the cited run ids exist locally.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any, Mapping

#: The append-only store index for reproduction attempts and adjudications.
REPRODUCTIONS_INDEX = "reproductions.jsonl"

#: What a report says happened when the named runs were re-executed.
OUTCOMES = (
    "byte_identical",  # every named run id regenerated byte-for-byte
    "diverged",  # at least one named run produced different bytes/numbers
    "incomplete",  # the walk stopped before the outcome could be established
)

#: The four independence criteria of the verification procedure
#: (docs/reproduction-policy.md §"What counts as independent").  Each is
#: judged exactly once, in an adjudication, with a note; an attempt may
#: not judge any of them (they default to null = UNKNOWN).
INDEPENDENCE_CRITERIA = (
    "distinct_hands",
    "distinct_machine",
    "released_artifacts_only",
    "public_report",
)

#: Adjudication verdicts.  ``externally_reproduced`` is gated (see module
#: docstring); the other two close an attempt without landing the label:
#: ``not_independent`` (a criterion failed or could not be established)
#: and ``not_counted`` (the attempt never reached a countable outcome).
VERDICTS = (
    "externally_reproduced",
    "not_independent",
    "not_counted",
)

#: Repository author identities — the mechanical floor of the
#: ``distinct_hands`` criterion.  An attempt whose reproducer matches one
#: of these cannot be adjudicated ``externally_reproduced``: the author's
#: own re-run is at best VERIFIED (CI / fresh-clone territory), never a
#: reproduction.  Extended as authorship grows; compared case-insensitively
#: after stripping a leading "@".
AUTHOR_IDENTITIES = ("li-ch", "li chen")

#: The effective label of an attempt with no (or non-qualifying)
#: adjudication.  A string, not a boolean, per the absence semantics of
#: :mod:`essun.evidence.dimensions`: unknown means "not established",
#: which is the honest state of every reproduction attempt until the
#: verification procedure runs.
UNKNOWN = "UNKNOWN"

#: Exactly the keys an attempt record may carry.
REPRODUCTION_FIELDS = (
    "reported",
    "report_url",
    "reproducer",
    "reproduced_at_commit",
    "environment",
    "outcome",
    "divergence_notes",
    "reproduced_run_ids",
    "independence",
)

#: Exactly the keys an adjudication record may carry.
ADJUDICATION_FIELDS = (
    "verdict",
    "adjudicator",
    "date",
    "basis",
    "independence",
)

_COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
_RUN_ID_RE = re.compile(r"^[0-9a-f]{64}$")
_DATE_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
_URL_RE = re.compile(r"^https?://")


class ReproductionError(ValueError):
    """Raised when a reproduction record or adjudication is malformed.

    A ``ValueError`` subclass on purpose, matching
    :class:`essun.evidence.dimensions.DimensionsError`: the evidence
    store catches it and re-raises as its own ``EvidenceError`` while the
    dimension-prefixed message passes through unchanged.
    """


# ---------------------------------------------------------------------------
# validation helpers
# ---------------------------------------------------------------------------


def _str_problems(field: str, value: Any) -> list[str]:
    if not isinstance(value, str) or not value:
        return [f"reproduction: {field} must be a non-empty string"]
    return []


def _date_problems(field: str, value: Any) -> list[str]:
    problems = _str_problems(field, value)
    if problems:
        return problems
    if not _DATE_RE.match(value):
        return [f"reproduction: {field} must be an ISO date (YYYY-MM-DD), got {value!r}"]
    return []


def _require_fields(record: Mapping, fields: tuple[str, ...], kind: str) -> list[str]:
    missing = [field for field in fields if field not in record]
    if missing:
        return [f"{kind}: missing field(s): {', '.join(missing)}"]
    unknown = [key for key in record if key not in fields]
    if unknown:
        return [f"{kind}: unknown field(s): {', '.join(sorted(unknown))}"]
    return []


def _hex_problems(field: str, value: Any, length: int) -> list[str]:
    problems = _str_problems(field, value)
    if problems:
        return problems
    pattern = {40: _COMMIT_RE, 64: _RUN_ID_RE}[length]
    if not pattern.match(value):
        return [
            f"reproduction: {field} must be {length} lowercase hex characters, "
            f"got {value!r}"
        ]
    return []


def _independence_null_problems(value: Any) -> list[str]:
    """Attempt-time independence: every present criterion must be null.

    A transcription reports; it does not judge.  Unknown criteria may be
    omitted entirely (absence is unknown), but a non-null value is a
    self-judgment and is rejected at the door.
    """
    if value is None:
        return []
    if not isinstance(value, dict):
        return ["reproduction: independence must be a mapping of criterion to null"]
    unknown = [key for key in value if key not in INDEPENDENCE_CRITERIA]
    if unknown:
        return [
            "reproduction: independence names unknown criterion(s): "
            f"{', '.join(sorted(unknown))}"
        ]
    judged = sorted(key for key, item in value.items() if item is not None)
    if judged:
        return [
            "reproduction: independence criteria are judged only by an "
            f"adjudication, attempt must leave them null (judged: {', '.join(judged)})"
        ]
    return []


def reproduction_problems(record: Any) -> list[str]:
    """All structural problems of an ATTEMPT record.

    Empty problems means the attempt is valid and recordable — which is
    NOT the same as label-bearing: see :func:`effective_label`.  Messages
    are ``reproduction:``-prefixed per the house style.  ``independence``
    is the one OPTIONAL field: present it must be all null (judgments
    belong to an adjudication); absent it reads as unknown, matching the
    schema and the D3 absence semantics.
    """
    if not isinstance(record, Mapping):
        return ["reproduction: must be a mapping"]
    required = tuple(field for field in REPRODUCTION_FIELDS if field != "independence")
    missing = [field for field in required if field not in record]
    if missing:
        return [f"reproduction: missing field(s): {', '.join(missing)}"]
    unknown = [key for key in record if key not in REPRODUCTION_FIELDS]
    if unknown:
        return [f"reproduction: unknown field(s): {', '.join(sorted(unknown))}"]
    problems: list[str] = []
    problems.extend(_date_problems("reported", record["reported"]))
    problems.extend(_str_problems("report_url", record["report_url"]))
    if not _URL_RE.match(record["report_url"]):
        problems.append(
            f"reproduction: report_url must be a public http(s) URL, got {record['report_url']!r}"
        )
    problems.extend(_str_problems("reproducer", record["reproducer"]))
    problems.extend(_hex_problems("reproduced_at_commit", record["reproduced_at_commit"], 40))
    problems.extend(_str_problems("environment", record["environment"]))
    if record["outcome"] not in OUTCOMES:
        problems.append(
            f"reproduction: outcome must be one of {OUTCOMES}, got {record['outcome']!r}"
        )
    run_ids = record["reproduced_run_ids"]
    if not isinstance(run_ids, list) or not run_ids:
        problems.append(
            "reproduction: reproduced_run_ids must be a non-empty list of run ids"
        )
    else:
        for index, run_id in enumerate(run_ids):
            problems.extend(
                _hex_problems(f"reproduced_run_ids[{index}]", run_id, 64)
            )
    notes = record["divergence_notes"]
    if record["outcome"] == "byte_identical":
        if notes is not None:
            problems.append(
                "reproduction: divergence_notes must be null when outcome is "
                "byte_identical (nothing diverged)"
            )
    elif not isinstance(notes, str) or not notes:
        problems.append(
            "reproduction: divergence_notes (what diverged, where minimized/"
            "classified) is required when outcome is not byte_identical"
        )
    problems.extend(_independence_null_problems(record.get("independence")))
    return problems


def validate_reproduction(record: Any) -> None:
    """Validate an attempt; raise on the first problem list."""
    problems = reproduction_problems(record)
    if problems:
        raise ReproductionError("; ".join(problems))


def _adjudication_independence_problems(value: Any) -> list[str]:
    """Adjudication-time independence: all four criteria, each judged.

    A judgment is ``{met: bool, note: non-empty string}`` — the note is
    what an auditor reads to re-derive the judgment, so an empty note is
    an unmade judgment.
    """
    if not isinstance(value, dict):
        return ["adjudication: independence must judge all four criteria"]
    missing = [name for name in INDEPENDENCE_CRITERIA if name not in value]
    if missing:
        return [f"adjudication: independence must judge: {', '.join(missing)}"]
    unknown = [key for key in value if key not in INDEPENDENCE_CRITERIA]
    if unknown:
        return [
            f"adjudication: independence names unknown criterion(s): {', '.join(sorted(unknown))}"
        ]
    problems: list[str] = []
    for name in INDEPENDENCE_CRITERIA:
        judgment = value[name]
        if not isinstance(judgment, dict):
            problems.append(
                f"adjudication: independence.{name} must be a mapping with 'met' and 'note'"
            )
            continue
        unknown_j = [key for key in judgment if key not in ("met", "note")]
        if unknown_j:
            problems.append(
                f"adjudication: independence.{name} has unknown field(s): "
                f"{', '.join(sorted(unknown_j))}"
            )
        if not isinstance(judgment.get("met"), bool):
            problems.append(f"adjudication: independence.{name}.met must be a boolean")
        problems.extend(
            _str_problems(f"independence.{name}.note", judgment.get("note"))
        )
    return problems


def adjudication_problems(record: Any, attempt: Mapping | None = None) -> list[str]:
    """All problems of an ADJUDICATION, optionally cross-checked against
    the attempt it adjudicates.

    The cross-check is where the never-asserted rule bites: a verdict of
    ``externally_reproduced`` is refused unless the attempt it judges has
    a ``byte_identical`` outcome, the reproducer is not an author
    identity, and every criterion is judged met.  Without the attempt
    (schema-only validation) the gate cannot run and the caller gets the
    structural problems alone — the store always passes the attempt.
    """
    if not isinstance(record, Mapping):
        return ["adjudication: must be a mapping"]
    problems = _require_fields(record, ADJUDICATION_FIELDS, "adjudication")
    if problems:
        return problems
    if record["verdict"] not in VERDICTS:
        problems.append(
            f"adjudication: verdict must be one of {VERDICTS}, got {record['verdict']!r}"
        )
    problems.extend(_str_problems("adjudicator", record["adjudicator"]))
    problems.extend(_date_problems("date", record["date"]))
    problems.extend(_str_problems("basis", record["basis"]))
    problems.extend(_adjudication_independence_problems(record["independence"]))
    if problems or attempt is None:
        return problems

    # Cross-field gates (need the attempt; the label lands only through here).
    if record["verdict"] == "externally_reproduced":
        if attempt.get("outcome") != "byte_identical":
            problems.append(
                "adjudication: verdict externally_reproduced requires a "
                f"byte_identical attempt, got outcome {attempt.get('outcome')!r}"
            )
        reproducer = str(attempt.get("reproducer", "")).lstrip("@").lower()
        if reproducer in AUTHOR_IDENTITIES:
            problems.append(
                "adjudication: verdict externally_reproduced refused — "
                f"reproducer {attempt.get('reproducer')!r} is a repository "
                "author identity; an author re-run is at best VERIFIED"
            )
        independence = record["independence"]
        unmet = [
            name
            for name in INDEPENDENCE_CRITERIA
            if not (isinstance(independence.get(name), dict) and independence[name].get("met") is True)
        ]
        if unmet:
            problems.append(
                "adjudication: verdict externally_reproduced requires every "
                f"independence criterion judged met (unmet: {', '.join(unmet)})"
            )
    return problems


def validate_adjudication(record: Any, attempt: Mapping | None = None) -> None:
    """Validate an adjudication (with attempt cross-check when given)."""
    problems = adjudication_problems(record, attempt)
    if problems:
        raise ReproductionError("; ".join(problems))


